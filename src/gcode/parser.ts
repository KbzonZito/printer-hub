import { KIND_INDEX, KINDS, kindFromType } from './kinds';
import type { GcodeLayer, GcodeSummary } from './model';

// Streaming G-code parser. It works on bytes (only a few comment lines are decoded to text),
// accepts the file in chunks of any size and hands back each layer as soon as it's complete.
// Pure: tested in Node, run in a Web Worker by the app. See docs/plans/vista-previa-gcode.md.

/** Bump when the model changes, so cached models (cache.ts) are read again. */
export const PARSER_VERSION = 1;

export interface ParserOptions {
  /** Maximum distance between an arc and its segments (mm). */
  arcTolerance?: number;
  /** Points closer than this to the previous one are dropped (mm). */
  minDistance?: number;
  /** Byte of the file where the first chunk starts (when parsing a range, D11). */
  startOffset?: number;
  /** Ignore everything before the first layer comment (when starting mid-file). */
  waitForLayer?: boolean;
}

const NL = 10;
const SEMI = 59;
const SPACE = 32;
const TAB = 9;
const CR = 13;
const MAX_ARC_SEGMENTS = 720;

const enc = new TextEncoder();
const dec = new TextDecoder();
const bytes = (s: string) => enc.encode(s);
const P = {
  layerChange: bytes(';LAYER_CHANGE'),
  layerCura: bytes(';LAYER:'),
  z: bytes(';Z:'),
  height: bytes(';HEIGHT:'),
  type: bytes(';TYPE:'),
  generated: bytes('; generated by '),
  totalLayers: bytes('; total layer number:'),
  maxZ: bytes('; max_z_height:'),
  layerHeight: bytes('; layer_height ='),
  filamentColour: bytes('; filament_colour ='),
  excludeDefine: bytes('EXCLUDE_OBJECT_DEFINE'),
  excludeStart: bytes('EXCLUDE_OBJECT_START'),
  excludeEnd: bytes('EXCLUDE_OBJECT_END'),
  name: bytes('NAME='),
};

function startsWith(buf: Uint8Array, i: number, end: number, p: Uint8Array) {
  if (end - i < p.length) return false;
  for (let k = 0; k < p.length; k++) if (buf[i + k] !== p[k]) return false;
  return true;
}

/** Growable typed-array builders (plain JS arrays are slower and twice the memory). */
class F32 {
  a = new Float32Array(256);
  n = 0;
  push(v: number) {
    if (this.n === this.a.length) {
      const b = new Float32Array(this.a.length * 2);
      b.set(this.a);
      this.a = b;
    }
    this.a[this.n++] = v;
  }
  take() {
    return this.a.slice(0, this.n);
  }
}
class U32 {
  a = new Uint32Array(64);
  n = 0;
  push(v: number) {
    if (this.n === this.a.length) {
      const b = new Uint32Array(this.a.length * 2);
      b.set(this.a);
      this.a = b;
    }
    this.a[this.n++] = v;
  }
}

interface LayerBuilder {
  z: number;
  height: number | null;
  start: number;
  /** Opened by a layer comment (or implicitly, by extrusion before the first comment). */
  fromComment: boolean;
  /** z came from ";Z:" (or the first extrusion); until then it's provisional. */
  zKnown: boolean;
  points: F32;
  polyStart: U32;
  polyOffset: U32;
  polyKind: number[];
  polyTool: number[];
  polyObject: number[];
  travel: F32;
}

export class GcodeParser {
  private arcTol: number;
  private minDist2: number;
  private waiting: boolean;

  // Position and modes (Klipper defaults: absolute XYZ and E).
  private x = 0;
  private y = 0;
  private z = 0;
  private e = 0;
  private absXYZ = true;
  private absE = true;

  // Attributes of the next polyline.
  private kind = KIND_INDEX.other;
  private tool = 0;
  private object = 0;
  /** The last move extruded, so the next extrusion continues the same polyline. */
  private pen = false;
  private lastPx = 0;
  private lastPy = 0;

  private layer: LayerBuilder | null = null;
  /** Layer comments seen: layers come from comments, not from Z changes. */
  private commentLayers = false;
  private pendingZ: number | null = null;
  private pendingHeight: number | null = null;

  private offset: number;
  private carry: Uint8Array | null = null;
  private done: GcodeLayer[] = [];
  private totalPoints = 0;

  private summary: GcodeSummary = {
    slicer: null,
    layersHint: null,
    layerHeight: null,
    maxZ: null,
    bounds: null,
    objects: [],
    tools: [],
    toolColors: [],
    kinds: 0,
    bytes: 0,
    points: 0,
  };
  private minX = Infinity;
  private minY = Infinity;
  private maxX = -Infinity;
  private maxY = -Infinity;

  constructor(opts: ParserOptions = {}) {
    this.arcTol = opts.arcTolerance ?? 0.05;
    const md = opts.minDistance ?? 0.02;
    this.minDist2 = md * md;
    this.offset = opts.startOffset ?? 0;
    this.waiting = opts.waitForLayer ?? false;
  }

  /** Feeds the next part of the file; returns the layers completed by it. */
  push(chunk: Uint8Array): GcodeLayer[] {
    let i = 0;
    if (this.carry) {
      // Finish the line cut at the end of the previous chunk.
      const nl = chunk.indexOf(NL);
      if (nl < 0) {
        const joined = new Uint8Array(this.carry.length + chunk.length);
        joined.set(this.carry);
        joined.set(chunk, this.carry.length);
        this.carry = joined;
        this.offset += chunk.length;
        return this.flush();
      }
      const line = new Uint8Array(this.carry.length + nl);
      line.set(this.carry);
      line.set(chunk.subarray(0, nl), this.carry.length);
      const lineStart = this.offset - this.carry.length;
      this.carry = null;
      this.line(line, 0, line.length, lineStart);
      i = nl + 1;
    }
    const base = this.offset;
    const len = chunk.length;
    while (i < len) {
      const nl = chunk.indexOf(NL, i);
      if (nl < 0) {
        this.carry = chunk.slice(i);
        break;
      }
      this.line(chunk, i, nl, base + i);
      i = nl + 1;
    }
    this.offset = base + len;
    return this.flush();
  }

  /** Ends the file; returns the last layers and the summary. */
  finish(): { layers: GcodeLayer[]; summary: GcodeSummary } {
    if (this.carry) {
      const c = this.carry;
      this.carry = null;
      this.line(c, 0, c.length, this.offset - c.length);
    }
    this.closeLayer(this.offset);
    const s = this.summary;
    s.bytes = this.offset;
    s.points = this.totalPoints;
    s.bounds = Number.isFinite(this.minX)
      ? { minX: this.minX, minY: this.minY, maxX: this.maxX, maxY: this.maxY }
      : null;
    return { layers: this.flush(), summary: { ...s, tools: [...s.tools].sort((a, b) => a - b) } };
  }

  /**
   * Continues at another byte of the file, keeping the modes and objects read so far (from
   * the header). Nothing is drawn until the next layer comment, since the position before it
   * is unknown. Layers not yet completed are dropped. Used to show the layer being printed
   * before the whole file has arrived (D11).
   */
  seek(offset: number) {
    this.carry = null;
    this.layer = null;
    this.done = [];
    this.pen = false;
    this.offset = offset;
    this.waiting = true;
  }

  /** Header data parsed so far (layer count, slicer…), for progress while loading. */
  peekSummary(): GcodeSummary {
    return { ...this.summary, points: this.totalPoints };
  }

  private flush() {
    const out = this.done;
    this.done = [];
    return out;
  }

  // ------------------------------------------------------------------ lines

  private line(buf: Uint8Array, i: number, end: number, fileOffset: number) {
    while (i < end && (buf[i] === SPACE || buf[i] === TAB)) i++;
    if (end > i && buf[end - 1] === CR) end--;
    if (i >= end) return;
    if (buf[i] === SEMI) return this.comment(buf, i, end, fileOffset);
    if (this.waiting) return;

    // Drop an inline comment ("G1 X10 ; move"). Searched within the line only: indexOf would
    // scan the rest of the chunk for every line.
    for (let k = i + 1; k < end; k++)
      if (buf[k] === SEMI) {
        end = k;
        break;
      }
    const c = buf[i] | 0x20; // lower-case letter
    if (c === 0x67 /* g */) {
      const code = readInt(buf, i + 1, end);
      const j = numEnd;
      if (code === 0 || code === 1) this.move(buf, j, end, fileOffset);
      else if (code === 2 || code === 3) this.arc(buf, j, end, fileOffset, code === 2);
      else if (code === 90) this.absXYZ = true;
      else if (code === 91) this.absXYZ = false;
      else if (code === 92) this.setPosition(buf, j, end);
      else if (code === 28) this.pen = false;
    } else if (c === 0x6d /* m */) {
      const code = readInt(buf, i + 1, end);
      if (code === 82) this.absE = true;
      else if (code === 83) this.absE = false;
    } else if (c === 0x74 /* t */) {
      const tool = readInt(buf, i + 1, end);
      if (numEnd > i + 1 && tool >= 0 && tool < 64) {
        this.tool = tool;
        this.pen = false;
        if (!this.summary.tools.includes(tool)) this.summary.tools.push(tool);
      }
    } else if (c === 0x65 /* e */) {
      if (startsWith(buf, i, end, P.excludeStart)) {
        this.object = this.objectIndex(readName(buf, i, end)) + 1;
        this.pen = false;
      } else if (startsWith(buf, i, end, P.excludeEnd)) {
        this.object = 0;
        this.pen = false;
      } else if (startsWith(buf, i, end, P.excludeDefine)) {
        this.objectIndex(readName(buf, i, end));
      }
    }
  }

  private comment(buf: Uint8Array, i: number, end: number, fileOffset: number) {
    if (startsWith(buf, i, end, P.layerChange) || startsWith(buf, i, end, P.layerCura)) {
      this.commentLayers = true;
      this.waiting = false;
      this.startLayer(fileOffset);
    } else if (startsWith(buf, i, end, P.z)) {
      const z = parseFloat(text(buf, i + P.z.length, end));
      if (Number.isFinite(z)) {
        if (this.layer?.fromComment) {
          this.layer.z = z;
          this.layer.zKnown = true;
        } else this.pendingZ = z;
      }
    } else if (startsWith(buf, i, end, P.height)) {
      const h = parseFloat(text(buf, i + P.height.length, end));
      // Slicers repeat ;HEIGHT: inside a layer (bridges…); the first one is the layer's.
      if (Number.isFinite(h) && this.layer?.fromComment) this.layer.height ??= h;
      else if (Number.isFinite(h)) this.pendingHeight ??= h;
    } else if (startsWith(buf, i, end, P.type)) {
      this.kind = kindFromType(text(buf, i + P.type.length, end));
      this.pen = false;
    } else if (startsWith(buf, i, end, P.generated)) {
      this.summary.slicer ??= text(buf, i + P.generated.length, end).replace(/ on \d{4}-.*$/, '');
    } else if (startsWith(buf, i, end, P.totalLayers)) {
      this.summary.layersHint = parseInt(text(buf, i + P.totalLayers.length, end)) || null;
    } else if (startsWith(buf, i, end, P.maxZ)) {
      this.summary.maxZ = parseFloat(text(buf, i + P.maxZ.length, end)) || null;
    } else if (startsWith(buf, i, end, P.layerHeight)) {
      this.summary.layerHeight ??= parseFloat(text(buf, i + P.layerHeight.length, end)) || null;
    } else if (startsWith(buf, i, end, P.filamentColour)) {
      this.summary.toolColors = text(buf, i + P.filamentColour.length, end)
        .split(/[;,]/)
        .map((c) => c.trim())
        .filter((c) => /^#[0-9a-f]{6}$/i.test(c));
    }
  }

  // ------------------------------------------------------------------ moves

  private move(buf: Uint8Array, i: number, end: number, fileOffset: number) {
    let nx = this.x;
    let ny = this.y;
    let nz = this.z;
    let de = 0;
    let hasXY = false;
    while (i < end) {
      const c = buf[i] | 0x20;
      if (c === 0x78 || c === 0x79 || c === 0x7a || c === 0x65) {
        const v = readNumber(buf, i + 1, end);
        i = numEnd;
        if (c === 0x78) {
          nx = this.absXYZ ? v : this.x + v;
          hasXY = true;
        } else if (c === 0x79) {
          ny = this.absXYZ ? v : this.y + v;
          hasXY = true;
        } else if (c === 0x7a) nz = this.absXYZ ? v : this.z + v;
        else if (this.absE) {
          de = v - this.e;
          this.e = v;
        } else de = v;
      } else i++;
    }
    if (nz !== this.z) {
      this.z = nz;
      this.pen = false;
    }
    if (!hasXY || (nx === this.x && ny === this.y)) return;
    if (de > 0) this.extrude(nx, ny, fileOffset);
    else this.travelTo(nx, ny);
  }

  private arc(buf: Uint8Array, i: number, end: number, fileOffset: number, clockwise: boolean) {
    let nx = this.x;
    let ny = this.y;
    let ci = 0;
    let cj = 0;
    let r = 0;
    let de = 0;
    while (i < end) {
      const c = buf[i] | 0x20;
      if (
        c === 0x78 ||
        c === 0x79 ||
        c === 0x69 ||
        c === 0x6a ||
        c === 0x72 ||
        c === 0x65 ||
        c === 0x7a
      ) {
        const v = readNumber(buf, i + 1, end);
        i = numEnd;
        if (c === 0x78) nx = this.absXYZ ? v : this.x + v;
        else if (c === 0x79) ny = this.absXYZ ? v : this.y + v;
        else if (c === 0x69) ci = v;
        else if (c === 0x6a) cj = v;
        else if (c === 0x72) r = v;
        else if (c === 0x7a) this.z = this.absXYZ ? v : this.z + v;
        else if (this.absE) {
          de = v - this.e;
          this.e = v;
        } else de = v;
      } else i++;
    }
    const sx = this.x;
    const sy = this.y;
    let cx: number;
    let cy: number;
    if (r !== 0) {
      // Radius form: center on the perpendicular bisector; negative R = the long way round.
      const dx = nx - sx;
      const dy = ny - sy;
      const d = Math.hypot(dx, dy);
      if (d === 0) return;
      const h = Math.sqrt(Math.max(0, r * r - (d * d) / 4));
      const sign = (clockwise ? 1 : -1) * (r > 0 ? 1 : -1);
      cx = (sx + nx) / 2 - (sign * h * dy) / d;
      cy = (sy + ny) / 2 + (sign * h * dx) / d;
    } else {
      cx = sx + ci;
      cy = sy + cj;
    }
    const radius = Math.hypot(sx - cx, sy - cy);
    if (radius < 1e-6) return;
    const a0 = Math.atan2(sy - cy, sx - cx);
    let a1 = Math.atan2(ny - cy, nx - cx);
    let sweep = a1 - a0;
    if (clockwise) {
      if (sweep >= -1e-9) sweep -= 2 * Math.PI;
    } else if (sweep <= 1e-9) sweep += 2 * Math.PI;
    a1 = a0 + sweep;
    const step = radius > this.arcTol ? 2 * Math.acos(1 - this.arcTol / radius) : Math.PI / 4;
    const n = Math.min(MAX_ARC_SEGMENTS, Math.max(1, Math.ceil(Math.abs(sweep) / step)));
    const extruding = de > 0;
    if (!extruding) return this.travelTo(nx, ny);
    for (let k = 1; k <= n; k++) {
      const px = k === n ? nx : cx + radius * Math.cos(a0 + (sweep * k) / n);
      const py = k === n ? ny : cy + radius * Math.sin(a0 + (sweep * k) / n);
      this.extrude(px, py, fileOffset);
    }
  }

  private setPosition(buf: Uint8Array, i: number, end: number) {
    let any = false;
    let moved = false;
    while (i < end) {
      const c = buf[i] | 0x20;
      if (c === 0x78 || c === 0x79 || c === 0x7a || c === 0x65) {
        const v = readNumber(buf, i + 1, end);
        i = numEnd;
        any = true;
        if (c === 0x65) this.e = v;
        else {
          moved = true;
          if (c === 0x78) this.x = v;
          else if (c === 0x79) this.y = v;
          else this.z = v;
        }
      } else i++;
    }
    if (!any) this.e = 0; // bare "G92" resets all; only E matters here
    // "G92 E0" (every layer in Creality Print) keeps the line going; moving XYZ breaks it.
    if (any && moved) this.pen = false;
  }

  private travelTo(nx: number, ny: number) {
    if (this.layer) {
      const t = this.layer.travel;
      t.push(this.x);
      t.push(this.y);
      t.push(nx);
      t.push(ny);
    }
    this.x = nx;
    this.y = ny;
    this.pen = false;
  }

  private extrude(nx: number, ny: number, fileOffset: number) {
    if (this.waiting) {
      this.x = nx;
      this.y = ny;
      return;
    }
    let l = this.layer;
    if (!l) l = this.openLayer(fileOffset, false);
    else if (!this.commentLayers && this.z > l.z + 0.005) {
      // No layer comments: a new layer starts when extrusion happens higher up (a Z hop
      // doesn't count, it doesn't extrude).
      this.closeLayer(fileOffset);
      l = this.openLayer(fileOffset, false);
    }
    if (!l.zKnown) {
      // Cura has no ";Z:": the layer is at the height of its first extrusion.
      l.z = this.z;
      l.zKnown = true;
    }
    if (!this.pen) {
      l.polyStart.push(l.points.n / 2);
      l.polyOffset.push(fileOffset);
      l.polyKind.push(this.kind);
      l.polyTool.push(this.tool);
      l.polyObject.push(this.object);
      l.points.push(this.x);
      l.points.push(this.y);
      this.lastPx = this.x;
      this.lastPy = this.y;
      this.bound(this.x, this.y);
      this.totalPoints++;
      this.summary.kinds |= 1 << this.kind;
      this.pen = true;
    }
    const dx = nx - this.lastPx;
    const dy = ny - this.lastPy;
    if (dx * dx + dy * dy >= this.minDist2) {
      l.points.push(nx);
      l.points.push(ny);
      this.lastPx = nx;
      this.lastPy = ny;
      this.bound(nx, ny);
      this.totalPoints++;
    }
    this.x = nx;
    this.y = ny;
  }

  private bound(x: number, y: number) {
    if (x < this.minX) this.minX = x;
    if (x > this.maxX) this.maxX = x;
    if (y < this.minY) this.minY = y;
    if (y > this.maxY) this.maxY = y;
  }

  // ------------------------------------------------------------------ layers

  private startLayer(fileOffset: number) {
    const l = this.layer;
    // Extrusion before the first layer comment (start G-code, purge line) joins that layer.
    if (l && !l.fromComment) {
      l.fromComment = true;
      l.zKnown = false;
      return;
    }
    if (l) this.closeLayer(fileOffset);
    this.openLayer(fileOffset, true);
  }

  private openLayer(fileOffset: number, fromComment: boolean): LayerBuilder {
    this.pen = false;
    this.layer = {
      z: this.pendingZ ?? this.z,
      height: this.pendingHeight,
      start: fileOffset,
      fromComment,
      zKnown: this.pendingZ != null || !fromComment,
      points: new F32(),
      polyStart: new U32(),
      polyOffset: new U32(),
      polyKind: [],
      polyTool: [],
      polyObject: [],
      travel: new F32(),
    };
    this.pendingZ = null;
    this.pendingHeight = null;
    return this.layer;
  }

  private closeLayer(fileOffset: number) {
    const l = this.layer;
    this.layer = null;
    this.pen = false;
    if (!l || (l.points.n === 0 && !l.fromComment)) return;
    this.done.push({
      z: l.z,
      height: l.height,
      start: l.start,
      end: fileOffset,
      points: l.points.take(),
      polyStart: l.polyStart.a.slice(0, l.polyStart.n),
      polyOffset: l.polyOffset.a.slice(0, l.polyOffset.n),
      polyKind: Uint8Array.from(l.polyKind),
      polyTool: Uint8Array.from(l.polyTool),
      polyObject: Uint16Array.from(l.polyObject),
      travel: l.travel.take(),
    });
  }

  private objectIndex(name: string) {
    if (!name) return -1;
    const objects = this.summary.objects;
    let i = objects.indexOf(name);
    if (i < 0) i = objects.push(name) - 1;
    return i;
  }
}

/** Number of kinds, for callers sizing per-kind arrays. */
export const KIND_COUNT = KINDS.length;

// ------------------------------------------------------------------ number helpers

/** Index after the last number read (avoids allocating a [value, index] pair per number). */
let numEnd = 0;

/** Reads "-12.5", ".377", "-.658" or "3" at buf[i]; the next index goes to numEnd. */
function readNumber(buf: Uint8Array, i: number, end: number): number {
  let neg = false;
  if (buf[i] === 45 /* - */) {
    neg = true;
    i++;
  } else if (buf[i] === 43 /* + */) i++;
  let v = 0;
  let div = 0;
  for (; i < end; i++) {
    const c = buf[i];
    if (c >= 48 && c <= 57) {
      v = v * 10 + (c - 48);
      if (div) div *= 10;
    } else if (c === 46 /* . */ && !div) div = 1;
    else break;
  }
  if (div > 1) v /= div;
  numEnd = i;
  return neg ? -v : v;
}

/** Reads an unsigned integer; -1 if there is none. The next index goes to numEnd. */
function readInt(buf: Uint8Array, i: number, end: number): number {
  let v = 0;
  const s = i;
  for (; i < end; i++) {
    const c = buf[i];
    if (c >= 48 && c <= 57) v = v * 10 + (c - 48);
    else break;
  }
  numEnd = i;
  return i > s ? v : -1;
}

function text(buf: Uint8Array, i: number, end: number) {
  return dec.decode(buf.subarray(i, end)).trim();
}

/** NAME=value (up to the next space) in an EXCLUDE_OBJECT_* line. */
function readName(buf: Uint8Array, i: number, end: number) {
  for (let k = i; k < end - P.name.length; k++) {
    if (startsWith(buf, k, end, P.name)) {
      let e = k + P.name.length;
      while (e < end && buf[e] !== SPACE && buf[e] !== TAB) e++;
      return text(buf, k + P.name.length, e).toUpperCase();
    }
  }
  return '';
}
