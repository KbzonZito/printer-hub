// Data the slicer writes in comments at the start (slicer, layers, thumbnails) and at the end
// (time, filament, temperatures) of a G-code file. Moonraker usually extracts it, but the Creality
// Hi's Moonraker doesn't recognise Creality Print files ("Unknown"), so the app reads it from
// the first and last kilobytes of the file (HTTP ranges) when it's missing.

export interface Thumbnail {
  width: number;
  height: number;
  /** data: URL of the image. */
  url: string;
}

export interface HeadInfo {
  slicer: string | null;
  layers: number | null;
  /** Complete thumbnails found, smallest first. */
  thumbnails: Thumbnail[];
}

export interface TailInfo {
  /** Seconds. */
  estimatedTime: number | null;
  filamentMm: number | null;
  filamentG: number | null;
  filamentType: string | null;
  nozzleTemp: number | null;
  bedTemp: number | null;
  printerModel: string | null;
}

/** "1d 2h 3m 4s", "17m 58s", "3h28m" → seconds. */
export function parseDuration(s: string): number | null {
  let total = 0;
  let any = false;
  for (const [, n, unit] of s.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/gi)) {
    total += Number(n) * { d: 86400, h: 3600, m: 60, s: 1 }[unit.toLowerCase() as 'd'];
    any = true;
  }
  return any ? Math.round(total) : null;
}

export function parseHead(text: string): HeadInfo {
  const slicer =
    text
      .match(/^; generated by (.+?)(?: on \d{4}-.*)?$/m)?.[1]
      ?.trim()
      .replace(/_/g, ' ') ??
    text.match(/^;\s*Generated with (.+)$/m)?.[1]?.trim() ??
    (/^;FLAVOR:/m.test(text) ? 'Cura' : null);
  const layers = Number(text.match(/^; total layer number: (\d+)/m)?.[1]) || null;
  const thumbnails: Thumbnail[] = [];
  const re =
    /^; thumbnail(?:_(PNG|JPG|QOI))? begin (\d+)x(\d+) (\d+)\r?\n([\s\S]*?)^; thumbnail(?:_\w+)? end/gm;
  for (const m of text.matchAll(re)) {
    const format = (m[1] ?? 'PNG').toUpperCase();
    if (format === 'QOI') continue; // browsers can't show QOI
    const data = m[5].replace(/^; ?/gm, '').replace(/\s+/g, '');
    if (data.length < Number(m[4]) * 0.9) continue; // cut off by the range
    thumbnails.push({
      width: Number(m[2]),
      height: Number(m[3]),
      url: `data:image/${format === 'JPG' ? 'jpeg' : 'png'};base64,${data}`,
    });
  }
  thumbnails.sort((a, b) => a.width - b.width);
  return { slicer, layers, thumbnails };
}

const num = (text: string, re: RegExp) => {
  const v = parseFloat(text.match(re)?.[1] ?? '');
  return Number.isFinite(v) ? v : null;
};

export function parseTail(text: string): TailInfo {
  const time =
    text.match(/^; estimated printing time \(normal mode\) = (.+)$/m)?.[1] ??
    text.match(/^; total estimated time: (.+)$/m)?.[1];
  const curaTime = num(text, /^;TIME:(\d+)/m);
  const curaFilamentM = num(text, /^;Filament used: ([\d.]+)m/m);
  const first = (s: string | undefined) => s?.split(/[;,]/)[0]?.trim() || null;
  return {
    estimatedTime: time ? parseDuration(time) : curaTime,
    filamentMm:
      num(text, /^; (?:total )?filament used \[mm\] = ([\d.]+)/m) ??
      (curaFilamentM != null ? curaFilamentM * 1000 : null),
    filamentG: num(text, /^; (?:total )?filament used \[g\] = ([\d.]+)/m),
    filamentType: first(text.match(/^; filament_type = (.+)$/m)?.[1]),
    nozzleTemp:
      num(text, /^; nozzle_temperature_initial_layer = (\d+)/m) ??
      num(text, /^; first_layer_temperature = (\d+)/m) ??
      num(text, /^; nozzle_temperature = (\d+)/m) ??
      num(text, /^; temperature = (\d+)/m),
    bedTemp:
      num(text, /^; hot_plate_temp_initial_layer = (\d+)/m) ??
      num(text, /^; first_layer_bed_temperature = (\d+)/m) ??
      num(text, /^; hot_plate_temp = (\d+)/m) ??
      num(text, /^; bed_temperature = (\d+)/m),
    printerModel: text.match(/^; printer_model = (.+)$/m)?.[1]?.trim() || null,
  };
}
